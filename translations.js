// إضافة مستمع للأحداث عند النقر على أحد خيارات اللغة
const languageItems = document.querySelectorAll('.dropdown-item');

languageItems.forEach(item => {
    item.addEventListener('click', (e) => {
        // منع الرابط من التفعيل (لن يحدث إعادة تحميل)
        e.preventDefault();

        // جلب اللغة المحددة من البيانات
        const selectedLang = e.target.getAttribute('data-lang');

        // تحديث اللغة في عنصر body
        document.body.setAttribute('lang', selectedLang);

        // تخزين اللغة في localStorage ليتم استخدامها لاحقاً
        localStorage.setItem('language', selectedLang);
    });
});

// جلب اللغة الحالية من localStorage أو تعيين الإنجليزية كإفتراضية
const currentLanguage = localStorage.getItem('language') || 'en';
document.body.setAttribute('lang', currentLanguage);


// تعيين الاتجاه بناءً على اللغة المختارة
document.querySelectorAll('.dropdown-item').forEach(item => {
    item.addEventListener('click', function() {
        let lang = item.getAttribute('data-lang');
        
        if (lang === 'ar') {
            // إضافة class rtl إذا كانت اللغة عربية
            document.body.classList.add('rtl');
            document.body.classList.remove('ltr');
        } else {
            // إضافة class ltr إذا كانت اللغة إنجليزية
            document.body.classList.add('ltr');
            document.body.classList.remove('rtl');
        }
    });
});



